#!/usr/bin/env node
// a24 KAF seed builder (pick-kaf-pool = build, [name] 2026-10-12).
//
// Reads the reviewed kaf-triage pool (two Medic reads per row) and writes a DATA
// ARTIFACT, never a migration:
//   scripts/sql/track-a/a24-exam/kaf-seed.sql           one guarded INSERT per runnable row
//   scripts/sql/track-a/a24-exam/kaf-seed.rollback.sql  deletes exactly those ids
//
// Runnable = both reads include or fix-then-include AND agree on key correctness
// (isTwoReadPass in src/lib/master-exam/pool.ts) AND stem_fix_needed is false,
// minus the rows whose live MC key is wrong (needs-track-a.json, live-key-defect);
// they stay out until their separate key fix lands.
// The rules below mirror pool.ts (isTwoReadPass, kafAcceptedAnswers); a unit test
// (tests/unit/a24-kaf/seed-builder.test.ts) keeps them equal.
//
// Usage: node scripts/content/kaf/build-seed.mjs [path/to/pool.json] [--check]
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(here, "../../..");
export const DEFAULT_POOL_PATH = "./reports/track-b-2026-10-11/data/kaf-triage/pool.json";
export const SEED_PATH = path.join(ROOT, "scripts/sql/track-a/a24-exam/kaf-seed.sql");
export const ROLLBACK_PATH = path.join(ROOT, "scripts/sql/track-a/a24-exam/kaf-seed.rollback.sql");

/** needs-track-a.json live-key-defect rows: wrong live MC key, held out until the key fix lands. */
export const EXCLUDED_KEY_FIX = Object.freeze([63854, 69784, 71616]);
export const SOURCE = "kaf-triage 2026-10-12 two Medic reads";
export const REVIEWED_BY = "medic-read1+read2";
export const REVIEWED_AT = "2026-10-12";
const TAG = "$a24kaf$";

const INCLUDE = new Set(["include", "fix-then-include"]);

export function isTwoReadPass(row) {
  return INCLUDE.has(row.read1.verdict) && INCLUDE.has(row.read2.verdict) && row.read1.key_correct === row.read2.key_correct;
}

function storedKeyConfirmed(row) {
  return row.read1.key_correct !== "no" && row.read2.key_correct !== "no";
}

/** Same order and dedupe as kafAcceptedAnswers: stored (when confirmed), read1, read2, read1 key points, read2 key points. */
export function acceptedAnswers(row) {
  const alternatives = [
    ...(storedKeyConfirmed(row) ? [row.stored_answer] : []),
    row.read1.model_answer,
    row.read2.model_answer,
    ...(row.read1.key_points ?? []),
    ...(row.read2.key_points ?? []),
  ]
    .map((s) => String(s ?? "").trim())
    .filter(Boolean);
  return [[...new Set(alternatives)]];
}

function unionKeyPoints(row) {
  const all = [...(row.read1.key_points ?? []), ...(row.read2.key_points ?? [])].map((s) => String(s ?? "").trim()).filter(Boolean);
  return [...new Set(all)];
}

/** Rows to seed, sorted by id, plus the counts recorded in the header. */
export function buildSeedRows(pool, excluded = EXCLUDED_KEY_FIX) {
  const rows = Array.isArray(pool) ? pool : pool.rows;
  const twoRead = rows.filter(isTwoReadPass);
  const stemReady = twoRead.filter((r) => r.stem_fix_needed !== true);
  const skip = new Set(excluded);
  const keyFixPresent = stemReady.filter((r) => skip.has(r.id)).map((r) => r.id);
  const seed = stemReady
    .filter((r) => !skip.has(r.id))
    .map((r) => ({
      question_id: r.id,
      accepted: acceptedAnswers(r),
      required: 1,
      model_answer: String(r.canonical_model_answer ?? "").trim(),
      key_points: unionKeyPoints(r),
    }))
    .sort((a, b) => a.question_id - b.question_id);
  for (const s of seed) {
    if (!Number.isInteger(s.question_id) || s.question_id <= 0) throw new Error(`bad id ${s.question_id}`);
    if (!s.model_answer) throw new Error(`row ${s.question_id}: empty canonical_model_answer`);
    if (s.accepted[0].length === 0) throw new Error(`row ${s.question_id}: no accepted wording`);
  }
  return {
    seed,
    counts: { rows: rows.length, twoRead: twoRead.length, stemReady: stemReady.length, keyFixPresent, emitted: seed.length },
  };
}

function dollar(text) {
  if (text.includes(TAG)) throw new Error("content contains the dollar-quote tag");
  return `${TAG}${text}${TAG}`;
}

export function renderSeed(pool, poolSha256) {
  const { seed, counts } = buildSeedRows(pool);
  const ids = seed.map((s) => s.question_id);
  const header = [
    "-- a24 KAF seed: DATA ARTIFACT, not a migration. track-A applies it once, after",
    "-- supabase/migrations/20261223090000_a24_kaf_items.sql, on a release GO.",
    "-- GENERATED by scripts/content/kaf/build-seed.mjs; do not edit by hand.",
    `-- pool.json file sha256: ${poolSha256} (rows_sha256 field: ${pool.rows_sha256 ?? "n/a"})`,
    `-- pool rows ${counts.rows}, two-read pass ${counts.twoRead}, stem_fix_needed false ${counts.stemReady},`,
    `-- held out for the live MC key fix (needs-track-a.json): ${EXCLUDED_KEY_FIX.join(", ")}`,
    `--   (present in the runnable set: ${counts.keyFixPresent.join(", ") || "none"}; the others already need a stem fix),`,
    `-- emitted rows: ${counts.emitted}.`,
    "-- accepted = kafAcceptedAnswers (stored wording only when both reads confirm it), required = 1,",
    "-- model_answer = canonical_model_answer, key_points = union of both reads.",
    "-- Every insert is skipped when the question is missing or inactive; reruns change nothing.",
    `-- Rollback: scripts/sql/track-a/a24-exam/kaf-seed.rollback.sql (deletes exactly these ${counts.emitted} ids).`,
    "",
    "BEGIN;",
  ];
  const inserts = seed.map((s) => [
    "INSERT INTO public.kaf_items (question_id, accepted, required, model_answer, key_points, source, reviewed_by, reviewed_at)",
    `SELECT ${s.question_id}, ${dollar(JSON.stringify(s.accepted))}::jsonb, ${s.required}, ${dollar(s.model_answer)}, ${dollar(JSON.stringify(s.key_points))}::jsonb,`,
    `       '${SOURCE}', '${REVIEWED_BY}', '${REVIEWED_AT}'::timestamptz`,
    `WHERE EXISTS (SELECT 1 FROM public.questions WHERE id = ${s.question_id} AND is_active)`,
    "ON CONFLICT (question_id) DO NOTHING;",
  ].join("\n"));
  const seedSql = [...header, "", inserts.join("\n\n"), "", "COMMIT;", ""].join("\n");
  const rollbackSql = [
    "-- Rollback for scripts/sql/track-a/a24-exam/kaf-seed.sql (a24 KAF seed data artifact).",
    "-- GENERATED by scripts/content/kaf/build-seed.mjs; do not edit by hand.",
    `-- pool.json file sha256: ${poolSha256} (rows_sha256 field: ${pool.rows_sha256 ?? "n/a"})`,
    `-- Deletes exactly the ${ids.length} seeded ids and nothing else.`,
    "BEGIN;",
    `DELETE FROM public.kaf_items WHERE question_id IN (${ids.join(", ")});`,
    "COMMIT;",
    "",
  ].join("\n");
  return { seedSql, rollbackSql, counts, ids };
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const args = process.argv.slice(2);
  const check = args.includes("--check");
  const poolPath = args.find((a) => !a.startsWith("--")) ?? DEFAULT_POOL_PATH;
  const bytes = readFileSync(poolPath);
  const sha = createHash("sha256").update(bytes).digest("hex");
  const { seedSql, rollbackSql, counts } = renderSeed(JSON.parse(bytes.toString("utf8")), sha);
  if (check) {
    const same = readFileSync(SEED_PATH, "utf8") === seedSql && readFileSync(ROLLBACK_PATH, "utf8") === rollbackSql;
    if (!same) { console.error("kaf-seed.sql is out of date; rerun build-seed.mjs"); process.exit(1); }
    console.log(`kaf seed up to date (${counts.emitted} rows)`);
  } else {
    writeFileSync(SEED_PATH, seedSql);
    writeFileSync(ROLLBACK_PATH, rollbackSql);
    console.log(`wrote ${counts.emitted} rows (pool ${counts.rows}, two-read ${counts.twoRead}, stem-ready ${counts.stemReady}, key-fix held ${counts.keyFixPresent.join(",") || "none"})`);
  }
}
