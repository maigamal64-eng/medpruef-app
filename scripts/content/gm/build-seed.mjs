#!/usr/bin/env node
// a44: generate the Gerichtsmedizin seed artifacts from the reviewed b27 set.
//
//   node scripts/content/gm/build-seed.mjs            write the artifacts
//   node scripts/content/gm/build-seed.mjs --check    exit 1 when a committed artifact differs
//
// Writes (all deterministic, no database access):
//   scripts/sql/track-a/a44-gm-delivery/gm-seed.sql           inserts 128 INACTIVE rows
//   scripts/sql/track-a/a44-gm-delivery/gm-seed.rollback.sql  deletes exactly them (refused while any is active or referenced)
//   scripts/sql/track-a/a44-gm-delivery/gm-seed.verify.sql    read-only id map for build-batches.mjs
//   reports/master-plan-2026-10-11/gm-delivery/receipts.json two Medic reads + rights per row, for the b20 gate
// Activation is never part of the seed: it runs through the b20 gate
// (scripts/content/activate_batch.mjs) on a release GO, in batches of at most 50.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { literal } from '../gate/emit.mjs';
import { COLUMNS, EXPECTED_ROWS, GM_SOURCE_FILE, GM_TOPIC, PINNED, loadReads, loadRights, loadRows, receipt, sha256 } from './lib.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../../..');
const SQL_DIR = resolve(ROOT, 'scripts/sql/track-a/a44-gm-delivery');
const REPORT_DIR = resolve(ROOT, 'reports/master-plan-2026-10-11/gm-delivery');
const TAG = '$a44gm$';

function value(col, v) {
  if (v === null || v === undefined) return 'NULL';
  if (col === 'choices') return `${literal(JSON.stringify(v))}::jsonb`;
  if (Array.isArray(v)) return v.length ? `ARRAY[${v.map(literal).join(', ')}]::text[]` : `'{}'::text[]`;
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (typeof v === 'number') { if (!Number.isSafeInteger(v)) throw new Error(`${col}: not an integer`); return String(v); }
  return literal(v);
}

export function build() {
  const items = loadRows();
  const reads = loadReads();
  loadRights();
  for (const { row } of items) {
    if (JSON.stringify(row).includes('$a44')) throw new Error('Row text contains the DO delimiter');
  }
  const ids = items.map((i) => i.row.anki_note_id);
  const idArray = `ARRAY[${ids.join(', ')}]::bigint[]`;
  const hashArray = `ARRAY[${items.map((i) => literal(i.row.content_hash)).join(', ')}]::text[]`;
  const src = literal(GM_SOURCE_FILE);
  const header = (what) => [
    `-- a44 Gerichtsmedizin ${what}: DATA ARTIFACT, not a migration. track-A runs it on a release GO only.`,
    '-- GENERATED by scripts/content/gm/build-seed.mjs; do not edit by hand (rerun with --check).',
    `-- Reviewed set: track-B b27 gm-set.json sha256 ${PINNED['gm-set.json']}`,
    `--   ${EXPECTED_ROWS} rows, each with two Content Medic APPROVE reads (medic-read-1 ${PINNED['medic-read-1.json'].slice(0, 12)}, medic-read-2 ${PINNED['medic-read-2.json'].slice(0, 12)}),`,
    `--   original authorship from Austrian statutes and open-access articles (rights-basis ${PINNED['rights-basis.json'].slice(0, 12)}).`,
    `-- Placement: decision:pick-gm-placement B. exam_type 'pharma', topic '${GM_TOPIC}', tag field:gerichtsmedizin, source_file ${GM_SOURCE_FILE}.`,
    '-- Actor and reason (ADM-15 A): recorded in the track-A apply receipt (release.md), never in this file.',
  ].join('\n');

  const valuesSql = items.map(({ row }) => `  (${COLUMNS.map((c) => value(c, row[c])).join(', ')})`).join(',\n');
  const expectedTuples = items.map(({ row }) => `(${row.anki_note_id}::bigint, ${literal(row.content_hash)}, ${literal(row.answer)})`).join(',\n    ');
  const seed = `${header('seed')}
-- Before: no row with these anki_note_ids. After: ${EXPECTED_ROWS} rows, all is_active = false.
-- A rerun inserts nothing and re-checks the content. Rollback: gm-seed.rollback.sql.

BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '60s';

DO ${TAG}
BEGIN
  IF EXISTS (SELECT 1 FROM public.questions WHERE anki_note_id = ANY(${idArray}) AND source_file IS DISTINCT FROM ${src}) THEN
    RAISE EXCEPTION 'a44 seed: a reserved anki_note_id belongs to another source';
  END IF;
  IF EXISTS (SELECT 1 FROM public.questions WHERE content_hash = ANY(${hashArray})
             AND (source_file IS DISTINCT FROM ${src} OR NOT (anki_note_id = ANY(${idArray})))) THEN
    RAISE EXCEPTION 'a44 seed: a stem already exists in the bank (duplicate content_hash)';
  END IF;
END
${TAG};

INSERT INTO public.questions (${COLUMNS.join(', ')})
VALUES
${valuesSql}
ON CONFLICT (anki_note_id) DO NOTHING;

DO ${TAG}
DECLARE n integer; drift integer;
BEGIN
  SELECT count(*) INTO n FROM public.questions
   WHERE anki_note_id = ANY(${idArray}) AND source_file = ${src} AND exam_type = 'pharma' AND topic = ${literal(GM_TOPIC)};
  IF n <> ${EXPECTED_ROWS} THEN RAISE EXCEPTION 'a44 seed: expected ${EXPECTED_ROWS} rows, found %', n; END IF;
  SELECT count(*) INTO drift FROM (VALUES
    ${expectedTuples}
  ) AS e(anki_note_id, content_hash, answer)
  LEFT JOIN public.questions q ON q.anki_note_id = e.anki_note_id
   AND q.content_hash = e.content_hash AND q.answer = e.answer
  WHERE q.id IS NULL;
  IF drift <> 0 THEN RAISE EXCEPTION 'a44 seed: % existing rows differ from the reviewed set', drift; END IF;
END
${TAG};

COMMIT;
`;

  const rollback = `${header('seed rollback')}
-- Deletes exactly the ${EXPECTED_ROWS} seeded rows and nothing else. Refused while any of them is
-- active (run the b20 batch rollback first) or referenced by learner data or the activation log.

BEGIN;
SET LOCAL lock_timeout = '5s';

DO ${TAG}
BEGIN
  IF EXISTS (SELECT 1 FROM public.questions WHERE anki_note_id = ANY(${idArray}) AND source_file = ${src} AND is_active IS DISTINCT FROM false) THEN
    RAISE EXCEPTION 'a44 seed rollback: a seeded row is active; roll back its activation batch first';
  END IF;
  IF EXISTS (SELECT 1 FROM public.answer_history h JOIN public.questions q ON q.id = h.question_id
             WHERE q.anki_note_id = ANY(${idArray}) AND q.source_file = ${src})
     OR EXISTS (SELECT 1 FROM public.user_question_progress p JOIN public.questions q ON q.id = p.question_id
             WHERE q.anki_note_id = ANY(${idArray}) AND q.source_file = ${src}) THEN
    RAISE EXCEPTION 'a44 seed rollback: learner data references a seeded row; keep it inactive instead';
  END IF;
END
${TAG};

DELETE FROM public.questions
 WHERE anki_note_id = ANY(${idArray}) AND source_file = ${src} AND is_active = false;

COMMIT;
`;

  const verify = `${header('seed id map (read-only)')}
-- Output (psql -A -t): anki_note_id|id|is_active|content_hash, one line per seeded row.
-- Feed it to scripts/content/gm/build-batches.mjs --ids <file>.
SELECT anki_note_id, id, is_active, content_hash
  FROM public.questions
 WHERE anki_note_id = ANY(${idArray}) AND source_file = ${src}
 ORDER BY anki_note_id;
`;

  const receipts = {
    note: 'Agent reference (a44). Per seeded row: the two Content Medic APPROVE reads and the rights record in the shape the b20 activation gate expects. reviewed_content_sha256 is reviewHash over the row as PostgreSQL returns it (jsonb key order). Ids are assigned by the seed; build-batches.mjs joins them by anki_note_id.',
    gm_set_sha256: PINNED['gm-set.json'],
    medic_reads: { 'medic-read-1.json': PINNED['medic-read-1.json'], 'medic-read-2.json': PINNED['medic-read-2.json'] },
    rows: items.map((item) => receipt(item, reads)),
  };
  return {
    files: {
      [resolve(SQL_DIR, 'gm-seed.sql')]: seed,
      [resolve(SQL_DIR, 'gm-seed.rollback.sql')]: rollback,
      [resolve(SQL_DIR, 'gm-seed.verify.sql')]: verify,
      [resolve(REPORT_DIR, 'receipts.json')]: JSON.stringify(receipts, null, 1) + '\n',
    },
    digest: sha256(seed),
  };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  const { files, digest } = build();
  let stale = 0;
  for (const [path, text] of Object.entries(files)) {
    if (check) {
      let current = null;
      try { current = readFileSync(path, 'utf8'); } catch { /* missing */ }
      if (current !== text) { stale++; console.error(`stale: ${path}`); }
    } else {
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, text);
    }
  }
  console.log(JSON.stringify({ rows: EXPECTED_ROWS, seed_sha256: digest, mode: check ? 'check' : 'write', stale }));
  process.exitCode = stale ? 1 : 0;
}
