/**
 * Credit awarded per qualified referral, in euro-cents. Default €40 = 4000.
 * Override with the REFERRAL_REWARD_CENTS env var for A/B testing or price
 * adjustments without a deploy. Note: the webhook qualification path uses
 * tiered per-plan amounts from referralPayoutCents() in nowpayments.ts;
 * this constant drives UI copy and any flat-reward display surfaces.
 */
export const REFERRAL_REWARD_CENTS = Number(process.env.REFERRAL_REWARD_CENTS) || 4000

/** Maximum stacked credit across all referrals, in euro-cents. €400 = 40000. */
export const REFERRAL_MAX_CREDIT_CENTS = 40_000

/** Public-facing site URL — the ?ref= link is hosted at the root. */
export const REFERRAL_SITE_URL = 'https://medpruf.com'

/** Chains supported for USDT / USDC payouts. */
export type PayoutWalletChain = 'TRC20' | 'ERC20' | 'POLYGON'

/** Payout methods stored on users.payout_method. */
export type PayoutMethod = 'crypto_wallet' | 'wise_account'

// ─────────────────────────────────────────────────────────────────────
// Code generation
// ─────────────────────────────────────────────────────────────────────

/**
 * Alphabet for referral codes — uppercase alphanumeric MINUS visually
 * confusing pairs (O/0, I/1, L). 30 symbols, 30^8 ≈ 6.56e11 codes.
 * Collision probability at 100k users ≈ 7.6e-3, at 1M ≈ 0.76 — low
 * enough that we only need to handle collisions via the DB UNIQUE
 * constraint + re-roll loop.
 */
const CODE_ALPHABET = 'ABCDEFGHJKMNPQRSTUVWXYZ23456789'
const CODE_LENGTH = 8

/** Generate one candidate referral code. */
export function generateReferralCode(): string {
  let out = ''
  for (let i = 0; i < CODE_LENGTH; i++) {
    const idx = Math.floor(Math.random() * CODE_ALPHABET.length)
    out += CODE_ALPHABET[idx]
  }
  return out
}

/**
 * Normalize a user-supplied referral code: uppercase, strip whitespace
 * and punctuation. Does NOT validate against the alphabet — that's a
 * DB lookup concern.
 */
export function normalizeReferralCode(raw: string): string {
  return raw.trim().toUpperCase().replace(/[^A-Z0-9]/g, '')
}

/**
 * Basic format check — is it plausibly a referral code? Codes must be
 * 4–12 chars of uppercase alphanumerics. Loose on length so legacy
 * 8-char codes generated by the baseline schema default
 * (`substr(md5(...), 1, 8)`, which may contain lowercase hex digits)
 * are accepted after uppercasing.
 */
export function isValidReferralCodeFormat(code: string): boolean {
  if (!code) return false
  if (code.length < 4 || code.length > 16) return false
  return /^[A-Z0-9]+$/.test(code)
}

// ─────────────────────────────────────────────────────────────────────
// Wallet / Wise validation
// ─────────────────────────────────────────────────────────────────────

/**
 * Validate a wallet address against its chain.
 *
 * Per the prompt: "basic regex, not full checksumming". We only want
 * to catch typos + completely-wrong-chain submissions. Real-world
 * verification happens at payout execution time (admin manually sends
 * a dust-tx first to confirm).
 *
 * - TRC20: starts with 'T', 33–34 base58 chars total (real Tron
 *   addresses are exactly 34 but we allow 33 for forgiveness).
 * - ERC20 / POLYGON: 0x + 40 hex chars (EVM standard).
 */
export function isValidWalletAddress(
  address: string,
  chain: PayoutWalletChain
): boolean {
  const a = address.trim()
  if (!a) return false
  switch (chain) {
    case 'TRC20':
      return /^T[A-HJ-NP-Za-km-z1-9]{32,33}$/.test(a)
    case 'ERC20':
    case 'POLYGON':
      return /^0x[a-fA-F0-9]{40}$/.test(a)
    default:
      return false
  }
}

/** RFC-ish email regex — same permissive shape we use elsewhere. */
export function isValidWiseEmail(email: string): boolean {
  const e = email.trim()
  if (!e || e.length > 254) return false
  return /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(e)
}

/** Allowed chain values for wallet payouts. */
export const PAYOUT_WALLET_CHAINS: PayoutWalletChain[] = [
  'TRC20',
  'ERC20',
  'POLYGON',
]

// ─────────────────────────────────────────────────────────────────────
// Masking for display
// ─────────────────────────────────────────────────────────────────────

/** Mask a wallet address for UI display — "TR9k...Xy4Q" style. */
export function maskWalletAddress(address: string): string {
  if (!address) return ''
  if (address.length <= 10) return address
  return `${address.slice(0, 4)}…${address.slice(-4)}`
}

/** Mask an email for UI display — "user-284e5882@example.com" style. */
export function maskEmail(email: string): string {
  if (!email) return ''
  const [local, domain] = email.split('@')
  if (!domain) return email
  if (local.length <= 3) return `${local}@${domain}`
  return `${local.slice(0, 2)}…${local.slice(-1)}@${domain}`
}

// ─────────────────────────────────────────────────────────────────────
// Referral-link helpers
// ─────────────────────────────────────────────────────────────────────

/** Build the public referral link for a code. */
export function buildReferralLink(code: string): string {
  const base =
    (typeof process !== 'undefined' && process.env?.NEXT_PUBLIC_SITE_URL) ||
    REFERRAL_SITE_URL
  return `${base.replace(/\/$/, '')}/?ref=${encodeURIComponent(code)}`
}
