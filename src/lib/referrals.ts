/**
 * Referral system shared logic.
 *
 * Context: MedPrüf goes paid on the June 26 Pharmakologie cycle via
 * crypto-only rails (NOWPayments/USDT). Lock #3 (2026-04-23) replaces
 * the flat €40/€400 model with tiered payouts — see
 * `referralPayoutCents` + `REFERRAL_ANNUAL_CAP_CENTS` in
 * src/lib/nowpayments.ts for the canonical amounts. Payout rails are
 * wallet or Wise (no bank-transfer rail offered — crypto-paying
 * Prüflinge often don't have an IBAN-addressable account):
 *   - crypto_wallet — USDT/USDC to user-supplied wallet (TRC20 / ERC20 / POLYGON)
 *   - wise_account — email-addressable Wise account
 *
 * This module centralizes:
 *   1. Referral-code generation (8-char uppercase alphanumeric)
 *   2. Payout-method validation (wallet regex per chain + Wise email)
 *   3. Legacy constants (kept for backward compatibility — new code
 *      should import from `@/lib/nowpayments`)
 *
 * The reward lifecycle lives in `public.referrals`:
 *   pending                 — referee signed up but hasn't paid yet
 *   qualified (in hold)     — referee paid, 30-day payout hold still active
 *   qualified (claimable)   — hold cleared, admin can execute payout
 *   rewarded                — payout executed (manual-admin for v1)
 */

