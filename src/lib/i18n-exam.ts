export type ExamCopyKey = keyof (typeof EXAM_COPY)["de"];

/** Exam copy in German or English with {placeholders}. Unknown languages read English. */
export function te(key: ExamCopyKey, lang: string, vars?: Record<string, string | number>): string {
  const table: Record<string, string> = lang === "de" ? EXAM_COPY.de : EXAM_COPY.en;
  let text = table[key] ?? EXAM_COPY.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) text = text.split(`{${k}}`).join(String(v));
  return text;
}

/** Copy language for the exam screens: German only for German, English otherwise. */
export function examLang(lang: string): ExamLang {
  return lang === "de" ? "de" : "en";
}
