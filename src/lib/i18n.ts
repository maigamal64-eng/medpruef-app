export type TranslationKey = keyof typeof translations

/**
 * Reviewed overlays for languages beyond de/en, loaded as a separate chunk
 * only when such a language is both chosen and reviewed (REVIEWED_LANGS), so
 * de/en learners never download them.
 */
const overlays: Partial<Record<Lang, Partial<Record<string, string>>>> = {}
export function registerOverlay(lang: Lang, dict: Partial<Record<string, string>> | undefined): void {
  if (dict) overlays[lang] = dict
}
function needsOverlay(lang: Lang): boolean {
  return lang !== 'de' && lang !== 'en' && REVIEWED_LANGS.includes(lang) && !overlays[lang]
}
async function loadOverlay(lang: Lang): Promise<void> {
  if (!needsOverlay(lang)) return
  const mod = await import('./i18n-extra')
  registerOverlay(lang, (mod.EXTRA_TRANSLATIONS as Partial<Record<Lang, Partial<Record<string, string>>>>)[lang])
}

/** Per-key fallback: reviewed overlay, then English, never German for a non-German choice, never a raw key. */
export function t(key: TranslationKey, lang: Lang = 'de'): string {
  const base = translations[key] as { de?: string; en?: string } | undefined
  return resolveString(base, lang, overlays[lang], key, translations.language_fallback.en).text
}

export function isRtl(lang: Lang): boolean { return renderedLanguage(lang).dir === 'rtl' }

export function getUiLang(): Lang {
  if (typeof window === 'undefined') return 'de'
  const explicit = safeStorage.getItem('medpruef-lang')
  if (isUiLanguage(explicit)) return explicit
  try {
    const account = JSON.parse(safeStorage.getItem('medpruef_session') || 'null');
    if (safeStorage.getItem('medpruef_session_token') && isUiLanguage(account?.user?.language_code)) return account.user.language_code;
  } catch { /* no account language to restore */ }
  const auto = safeStorage.getItem('medpruef-lang-auto')
  if (isUiLanguage(auto)) return auto
  // Public-route default remains behind PUB-03. In-app detection is separate.
  const publicRoute = /^(\/landing|\/pricing|\/faq|\/terms|\/privacy|\/impressum|\/about|\/blog|\/stichprobentest|\/kenntnispruefung|\/pharmakologie)(\/|$)/.test(window.location.pathname)
  if (publicRoute) return 'de'
  const detected = detectLanguage(navigator.languages || [navigator.language])
  safeStorage.setItem('medpruef-lang-auto', detected)
  return detected
}

export function getLang(): 'de' | 'en' { return renderLang(getUiLang()) }

const LANG_EVENT = 'medpruef-lang-change'

export function setLang(lang: Lang) {
  if (typeof window !== 'undefined') {
    safeStorage.setItem('medpruef-lang', lang)
    document.cookie = `mp_lang=${lang}; path=/; max-age=31536000; SameSite=Lax`
    try {
      window.dispatchEvent(new CustomEvent<Lang>(LANG_EVENT, { detail: lang }))
    } catch {
      /* noop */
    }
  }
}

/**
 * React hook that returns the current language and re-renders whenever
 * setLang() is called anywhere in the app. Safe for SSR — returns 'de'
 * until the client mounts. Use this in shared components (modals,
 * toasts, floaters) so they honor the global language choice without
 * each page having to prop-drill `lang` down.
 */
export function useLang(): Lang {
  const [lang, setLangLocal] = useState<Lang>('de')
  useEffect(() => {
    let alive = true
    const apply = (next: Lang) => {
      if (!needsOverlay(next)) { setLangLocal(next); return }
      // Keep the current strings until the reviewed overlay chunk arrives.
      void loadOverlay(next).catch(() => undefined).finally(() => { if (alive) setLangLocal(next) })
    }
    apply(getUiLang())
    const handler = (e: Event) => {
      const detail = (e as CustomEvent<Lang>).detail
      if (detail && isUiLanguage(detail)) {
        apply(detail)
      } else {
        apply(getUiLang())
      }
    }
    const storageHandler = (e: StorageEvent) => {
      if (e.key === 'medpruef-lang') {
        apply(getUiLang())
      }
    }
    window.addEventListener(LANG_EVENT, handler)
    window.addEventListener('storage', storageHandler)
    return () => {
      alive = false
      window.removeEventListener(LANG_EVENT, handler)
      window.removeEventListener('storage', storageHandler)
    }
  }, [])
  return lang
}
