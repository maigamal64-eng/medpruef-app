-- W3-SEC-GRANTS (2026-10-10): explicit GRANTs for every MedPruef table, view
-- and sequence in schema public, ahead of Supabase's 30 Oct 2026 change.
--
-- WHY: from 30 Oct 2026 Supabase stops auto-granting NEW tables in public to the
-- API roles; any new table (including one created by a migration) needs an
-- explicit GRANT before PostgREST can reach it. Existing tables keep their
-- grants. Most MedPruef tables only have access today because of the old
-- default privileges, so this file writes down the access the app actually
-- needs: service_role (the app's role) on every MedPruef object, plus the one
-- narrow public read on questions metadata that example.com uses. A replay
-- of supabase/migrations on a fresh project after 30 Oct yields that
-- least-privilege ACL, and the file is the reference for future tables.
--
-- VARIANT (R4-05, decision:pick-grants-variant pick A, 2026-10-11): sections 1
-- and 5 grant to service_role ONLY. The generated file (gen-grants.mjs)
-- restated today's anon/authenticated ALL on the 54 tables and USAGE, SELECT,
-- UPDATE on the 17 sequences; that was the accidental default-privilege state,
-- not a requirement (every app read goes through /api/* with the service role,
-- and deny-all RLS already gives anon/authenticated no rows). Sections 2-4 are
-- unchanged, so anon/authenticated keep SELECT on questions(id, is_active,
-- exam_type, topic) only.
--
-- WHAT IT DOES ON PRODUCTION: nothing. Every statement grants a privilege the
-- role already holds (snapshot 2026-10-10, md5 f33534951bc00480bfa4672847c84423 over the query
-- at the bottom of this file). There is no REVOKE, so the existing anon and
-- authenticated grants on production stay as they are; removing them is the
-- separate, optional overnight/W3-SEC-GRANTS/optional-tighten-anon.sql
-- decision. No ALTER DEFAULT PRIVILEGES, no table outside MedPruef.
-- Generated by reports/plan-2026-10-10/overnight/W3-SEC-GRANTS/gen-grants.mjs
-- from the read-only inventory reports/plan-2026-10-10/security/grants-inventory.json,
-- then sections 1 and 5 narrowed by hand to the R4-05 variant.
-- Consequence: a fresh replay is tighter than production by design, so the
-- local-dryrun.sh B1 check ("replay == prod ACL") no longer applies to this
-- file; the post-apply md5 on production is unaffected.
--
-- SCOPE (one object per line, by name; nothing else is touched):
--   * 54 MedPruef tables: service_role ALL only (deny-all RLS for
--     anon/authenticated, service_role is the app's role).
--   * public.questions: service_role ALL, anon/authenticated column SELECT only.
--   * public.question_popularity (view): service_role only.
--   * public.whop_paid_grant_receipts: service_role SELECT, INSERT only.
--   * 17 MedPruef sequences: USAGE, SELECT, UPDATE to service_role only.
-- DELIBERATELY NOT TOUCHED:
--   * the 11 ops_* tables (postgres only by design, see 20261005150000) and
--     ops_audit_id_seq;
--   * public.owner_audit_log and its sequence (example.com, not MedPruef);
--   * every other schema ([name], blink, blinkos, booking_demo, henna, ...);
--   * functions (EXECUTE grants are set per function by their own migrations).
--
-- APPLY: as role postgres (the owner of every object here), only after
-- [name]'s explicit yes, before 30 Oct 2026. On PG 17 'ALL' on a table is
-- arwdDxtm (incl. MAINTAIN), which is exactly today's service_role entry.
--
-- RULE FOR NEW TABLES (mentor and anything after this file): each CREATE TABLE
-- migration must carry its own GRANT lines, least privilege, e.g.
--   ALTER TABLE public.<t> ENABLE ROW LEVEL SECURITY;
--   REVOKE ALL ON TABLE public.<t> FROM PUBLIC, anon, authenticated;
--   GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.<t> TO service_role;
--   GRANT USAGE, SELECT ON SEQUENCE public.<t>_id_seq TO service_role; -- if serial

