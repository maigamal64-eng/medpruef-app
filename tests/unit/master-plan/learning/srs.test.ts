import { describe, expect, it } from "vitest";
import { readFileSync } from "node:fs";
import path from "node:path";
import {
  BINARY_BUTTON_LABELS,
  MAX_INTERVAL_DAYS,
  SRS_CLAIM,
  binaryNext,
  examCapDays,
  gradeIsCorrect,
  gradedNext,
  intervalLabel,
  isLegacyExtremeInterval,
  nextReviewAt,
  previewGraded,
  roundHalfEven,
  type Grade,
} from "@/lib/master-learning/srs";

interface GoldenRow {
  ease: number | null;
  interval: number | null;
  grade: Grade;
  exam: string | null;
  outEase: number;
  outInterval: number;
}
const golden = JSON.parse(
  readFileSync(path.join(__dirname, "srs-golden.json"), "utf8"),
) as { today: string; rows: GoldenRow[] };

describe("srs graded scheduler", () => {
  it("matches the golden table generated by srs_graded_next on Postgres 16", () => {
    expect(golden.rows.length).toBe(960);
    for (const row of golden.rows) {
      const got = gradedNext({ ease: row.ease, intervalDays: row.interval }, row.grade, {
        todayIso: golden.today,
        examDate: row.exam,
      });
      expect({ k: row, ease: got.ease, days: got.intervalDays }).toEqual({
        k: row,
        ease: row.outEase,
        days: row.outInterval,
      });
    }
  });

  it("a record_graded_answer run on local Postgres 16 equals the repeated gradedNext steps", () => {
    // Observed on Postgres 16.13, user without exam date, grades 2,2,2,3,1,0,2.
    const observed: [Grade, number, number][] = [
      [2, 2.5, 1],
      [2, 2.5, 6],
      [2, 2.5, 15],
      [3, 2.65, 52],
      [1, 2.5, 62],
      [0, 2.3, 0],
      [2, 2.3, 1],
    ];
    let state: { ease: number | null; intervalDays: number | null } | null = null;
    for (const [grade, ease, days] of observed) {
      const r = gradedNext(state, grade);
      expect(r.intervalDays).toBe(days);
      expect(r.ease).toBeCloseTo(ease, 10);
      state = { ease: r.ease, intervalDays: r.intervalDays };
    }
    // Same run with an exam in 10 days: the cap holds at 8 (exam date minus 2 days).
    const capped = [2, 2, 3, 3].reduce<{ state: { ease: number | null; intervalDays: number | null } | null; out: number[] }>(
      (acc, g) => {
        const r = gradedNext(acc.state, g as Grade, { todayIso: "2026-10-12", examDate: "2026-10-22" });
        return { state: { ease: r.ease, intervalDays: r.intervalDays }, out: [...acc.out, r.intervalDays] };
      },
      { state: null, out: [] },
    );
    expect(capped.out).toEqual([1, 6, 8, 8]);
  });

  it("golden table covers every grade, the 180 day cap and the exam cap", () => {
    const grades = new Set(golden.rows.map((r) => r.grade));
    expect([...grades].sort()).toEqual([0, 1, 2, 3]);
    expect(Math.max(...golden.rows.map((r) => r.outInterval))).toBeLessThanOrEqual(MAX_INTERVAL_DAYS);
    expect(golden.rows.some((r) => r.exam !== null && r.outInterval === 0 && r.grade === 2)).toBe(true);
  });

  it("again resets, hard x1.2, good 1 then 6 then x ease, easy adds the bonus", () => {
    expect(gradedNext(null, 0).intervalDays).toBe(0);
    expect(gradedNext(null, 1).intervalDays).toBe(1);
    expect(gradedNext(null, 2).intervalDays).toBe(1);
    expect(gradedNext({ ease: 2.5, intervalDays: 1 }, 2).intervalDays).toBe(6);
    expect(gradedNext({ ease: 2.5, intervalDays: 6 }, 2).intervalDays).toBe(15);
    expect(gradedNext({ ease: 2.5, intervalDays: 10 }, 1).intervalDays).toBe(12);
    expect(gradedNext({ ease: 2.5, intervalDays: 10 }, 3).intervalDays).toBeGreaterThan(
      gradedNext({ ease: 2.5, intervalDays: 10 }, 2).intervalDays,
    );
  });

  it("ease stays between 1.3 and 3.0", () => {
    expect(gradedNext({ ease: 1.3, intervalDays: 3 }, 0).ease).toBe(1.3);
    expect(gradedNext({ ease: 3.0, intervalDays: 30 }, 3).ease).toBe(3.0);
  });

  it("caps by 180 days and by the exam date minus two days", () => {
    const far = gradedNext({ ease: 3.0, intervalDays: 170 }, 2, { todayIso: "2026-10-12", examDate: "2028-01-01" });
    expect(far.intervalDays).toBe(MAX_INTERVAL_DAYS);
    expect(far.cappedBy).toBe("max_interval");
    const near = gradedNext({ ease: 2.5, intervalDays: 30 }, 2, { todayIso: "2026-10-12", examDate: "2026-11-13" });
    expect(near.intervalDays).toBe(30);
    expect(near.cappedBy).toBe("exam_date");
    expect(examCapDays("2026-10-12", "2026-10-13")).toBe(0);
    expect(examCapDays("2026-10-12", null)).toBeNull();
  });

  it("rounds half to even like PostgreSQL round(double precision)", () => {
    expect(roundHalfEven(2.5)).toBe(2);
    expect(roundHalfEven(3.5)).toBe(4);
    expect(roundHalfEven(2.4999)).toBe(2);
    expect(roundHalfEven(2.5001)).toBe(3);
  });

  it("previews the interval the stored result will have, label included", () => {
    const state = { ease: 2.5, intervalDays: 6 };
    const preview = previewGraded(state, "de");
    expect(preview.good.intervalDays).toBe(gradedNext(state, 2).intervalDays);
    expect(preview.again.label).toBe("Kommt heute wieder");
    expect(intervalLabel(1, "de")).toBe("Wiederholung morgen");
    expect(intervalLabel(15, "en")).toBe("Review in 15 days");
  });
});

describe("srs binary scheduler (what runs today)", () => {
  it("binaryNext matches the stored RPC arithmetic", () => {
    // record_quiz_answer, 20260925190000_atomic_quiz_answer.sql L56-76
    expect(binaryNext(null, true)).toMatchObject({ ease: 2.6, intervalDays: 1 });
    expect(binaryNext(null, false)).toMatchObject({ ease: 2.3, intervalDays: 0 });
    // existing row: ease +0.1 (cap 3.0), interval max(1, round(prev x new ease))
    const second = binaryNext({ ease: 2.6, intervalDays: 1 }, true);
    expect(second.ease).toBeCloseTo(2.7, 10);
    expect(second.intervalDays).toBe(3);
    expect(binaryNext({ ease: 2.9, intervalDays: 10 }, true)).toMatchObject({ ease: 3.0, intervalDays: 30 });
    // after a lapse (interval 0) a correct answer gives 1 day
    expect(binaryNext({ ease: 2.3, intervalDays: 0 }, true).intervalDays).toBe(1);
    // wrong: ease -0.2 floor 1.3, due now
    expect(binaryNext({ ease: 1.4, intervalDays: 12 }, false)).toMatchObject({ ease: 1.3, intervalDays: 0 });
    // null columns fall back to 2.5 and 0
    expect(binaryNext({ ease: null, intervalDays: null }, true).ease).toBeCloseTo(2.6, 10);
  });

  it("good and easy count as right for the binary history, again and hard as wrong", () => {
    expect([0, 1, 2, 3].map((g) => gradeIsCorrect(g as Grade))).toEqual([false, false, true, true]);
  });

  it("the honest claim and the free binary labels are fixed strings", () => {
    expect(SRS_CLAIM.de).toBe("Wiederholungsplanung (angelehnt an SM-2)");
    expect(BINARY_BUTTON_LABELS.de.right).toBe("Gewusst");
    expect(BINARY_BUTTON_LABELS.de.wrong).toBe("Nicht gewusst");
  });

  it("flags legacy intervals above 180 days without rewriting them", () => {
    expect(isLegacyExtremeInterval(181)).toBe(true);
    expect(isLegacyExtremeInterval(180)).toBe(false);
    expect(isLegacyExtremeInterval(null)).toBe(false);
  });

  it("nextReviewAt adds whole days", () => {
    const now = new Date("2026-10-12T10:00:00Z");
    expect(nextReviewAt(now, 3).toISOString()).toBe("2026-10-15T10:00:00.000Z");
  });
});
