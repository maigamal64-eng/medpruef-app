/**
 * b37 language gate. For each live UI language and each public learner route:
 * seed medpruef-lang, load the page, and fail on English or German UI
 * sentences outside the allowlist. Known pre-existing gaps live in
 * known-gaps.json (route|lang -> count); the gate fails on any NEW leak, and
 * on a known gap that has been fixed (so the baseline only shrinks).
 *
 * Read-only: every non-GET/HEAD request is aborted (any origin) (local servers talk to
 * the production database). Allowlist of mutating routes: none.
 *
 * RTL screenshots (ar, 375x812) go to RTL_OUT (default tests/e2e/.artifacts/rtl).
 */
import { expect, test } from "@playwright/test";
import fs from "node:fs";
import path from "node:path";
import { findLeaks, LANGS, RTL } from "../../../../scripts/master-language/detect.mjs";

const allow = JSON.parse(
  fs.readFileSync(path.join(process.cwd(), "scripts/master-language/allowlist.json"), "utf8"),
) as { phrases: string[]; routes_de_only: string[] };
const knownPath = path.join(__dirname, "known-gaps.json");
const known: Record<string, number> = fs.existsSync(knownPath)
  ? JSON.parse(fs.readFileSync(knownPath, "utf8")).gaps
  : {};
const WRITE_BASELINE = process.env.LANG_GATE_WRITE_BASELINE === "1";
const observed: Record<string, number> = {};
const RTL_OUT = process.env.RTL_OUT ?? path.join(process.cwd(), "tests/e2e/.artifacts/rtl");

const ROUTES = [
  "/", "/pricing", "/login", "/about", "/faq", "/landing", "/curriculum",
  "/kenntnispruefung-wien", "/find-your-path", "/stichprobentest",
  "/pharmakologie-pruefung-wien", "/privacy", "/terms", "/impressum", "/changelog",
];
const deOnly = (r: string) => allow.routes_de_only.some((x) => r === x || r.startsWith(x + "/"));

test.beforeEach(async ({ page }) => {
  // Any non-GET/HEAD request to any origin is aborted: covers /api, Next server actions
  // (POST to the page URL) and direct Supabase calls.
  await page.route("**/*", (route) =>
    ["GET", "HEAD"].includes(route.request().method()) ? route.continue() : route.abort(),
  );
});

for (const lang of LANGS as string[]) {
  for (const route of ROUTES) {
    test(`${lang} ${route}`, async ({ page }) => {
      await page.setViewportSize({ width: 375, height: 812 });
      await page.addInitScript((l) => {
        try {
          localStorage.setItem("medpruef-lang", l);
          localStorage.setItem("medpruef_cookies", "declined");
        } catch { /* ignore */ }
      }, lang);
      const res = await page.goto(route, { waitUntil: "domcontentloaded" });
      expect(res?.status(), `status for ${route}`).toBeLessThan(400);
      await page.waitForLoadState("networkidle", { timeout: 15_000 }).catch(() => {});
      await page.waitForTimeout(600);

      const htmlLang = await page.evaluate(() => document.documentElement.lang);
      if (!deOnly(route)) expect(htmlLang, "html lang follows the picker").toBe(lang);

      if ((RTL as Set<string>).has(lang)) {
        const dir = await page.evaluate(
          () => document.documentElement.dir || document.body.getAttribute("dir") || "",
        );
        expect.soft(dir, `RTL dir on ${route}`).toBe("rtl");
        fs.mkdirSync(RTL_OUT, { recursive: true });
        const name = route === "/" ? "home" : route.replace(/^\//, "").replace(/\//g, "_");
        await page.screenshot({ path: path.join(RTL_OUT, `${name}-ar-375.png`), fullPage: true });
      }
      if (deOnly(route)) return;

      const text = await page.evaluate(() => {
        // Live DOM so innerText keeps block breaks and drops hidden text; skipped nodes are hidden then restored.
        const skip = Array.from(document.querySelectorAll<HTMLElement>("[data-question-text],[data-lang-skip]"));
        const prev = skip.map((n) => n.style.display);
        skip.forEach((n) => { n.style.display = "none"; });
        const out = document.body.innerText || "";
        skip.forEach((n, i) => { n.style.display = prev[i]; });
        return out;
      });
      const leaks = findLeaks(text, lang, allow.phrases) as { sentence: string; detected: string }[];
      const key = `${route}|${lang}`;
      observed[key] = leaks.length;
      if (WRITE_BASELINE) return;
      const allowedCount = known[key] ?? 0;
      const detail = leaks.slice(0, 8).map((l) => `[${l.detected}] ${l.sentence}`).join("\n");
      expect(leaks.length, `new language leaks on ${key} (baseline ${allowedCount}):\n${detail}`).toBeLessThanOrEqual(allowedCount);
      expect(leaks.length, `${key} improved below its baseline ${allowedCount}: lower known-gaps.json`).toBeGreaterThanOrEqual(allowedCount);
    });
  }
}

test.afterAll(() => {
  if (!WRITE_BASELINE) return;
  const gaps = Object.fromEntries(Object.entries(observed).filter(([, n]) => n > 0).sort());
  fs.writeFileSync(knownPath, JSON.stringify({ note: "Generated by LANG_GATE_WRITE_BASELINE=1. Lower counts only.", gaps }, null, 2) + "\n");
});
